"""Text-only benchmark of the three Telugu–English candidates for the 3D glasses story (no voice, no API call).

Usage:  <python with pydantic> colab/tenglish_candidates.py [stories/three_d_friends_te_v3] [--out reports/x.md]

B = story.json (mode "natural"); A and C (candidates.json) replace only the spoken text of the same turns, so
scenes, beats, fact ids, English source_text and visuals are identical. Each candidate is checked by the
Telugu critic in ITS OWN mode and in the selected mode, plus the six-way evaluation (telugu_dialogue.evaluate).
The numbers are measurable proxies; humour and naturalness are finally judged by a native speaker.
"""
import argparse, copy, json, logging, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "engine" / "lib"))
import characters, story, telugu_dialogue as td  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("folder", nargs="?", default=str(HERE / "stories" / "three_d_friends_te_v3"))
ap.add_argument("--out", default=str(HERE.parent / "reports" / "tenglish_candidates.md"))
a = ap.parse_args()
out = Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
logging.basicConfig(filename=str(out.with_suffix(".log")), level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
t0 = time.time()
folder = Path(a.folder)
raw = json.loads((folder / "story.json").read_text())
cand = json.loads((folder / "candidates.json").read_text())
bible = characters.load()
glossary = raw.get("glossary", {})


def variant(turns):
    r = copy.deepcopy(raw)
    for s in r["scenes"]:
        for k, t in enumerate(s["turns"]):
            t["text"] = turns.get(f"{s['id']}_{k + 1}", t["text"])
    return story.Story.model_validate(r)


C = {"A": (cand["A"]["code_mix"], variant(cand["A"]["turns"])),
     "B": (raw["code_mix"], story.Story.model_validate(raw)),
     "C": (cand["C"]["code_mix"], variant(cand["C"]["turns"]))}
rows, detail = [], []
for name, (mode, st) in C.items():
    ev = td.evaluate(st, bible, mode, glossary)
    ev_b = td.evaluate(st, bible, raw["code_mix"], glossary)          # judged by the selected (natural) standard
    struct = story.check_story(st, bible, target_s=80)
    n_words = sum(len(t.text.split()) for s in st.scenes for t in s.turns)
    rows.append((name, mode, ev["scores"], len(ev["required"]), len(ev["issues"]) - len(ev["required"]),
                 len(ev_b["required"]), sum(i["level"] == "error" for i in struct), n_words))
    detail.append((name, mode, st, ev, ev_b))
    logging.info("%s (%s): scores %s, required %d, natural-mode required %d", name, mode, ev["scores"],
                 len(ev["required"]), len(ev_b["required"]))

L = ["# Telugu–English candidates A / B / C (text only)", "",
     f"Generated by `colab/tenglish_candidates.py` in {time.time() - t0:.1f}s. Scores are deterministic 0–5 proxies "
     "(`telugu_dialogue.evaluate`); humour and naturalness still need a native speaker.", "",
     "| Candidate | Mode | " + " | ".join(td.CRITERIA) + " | Errors (own mode) | Warnings | Errors (natural mode) | "
     "Story-rule errors | Words |", "|---" * (len(td.CRITERIA) + 7) + "|"]
for name, mode, sc, req, warn, req_b, se, nw in rows:
    L.append(f"| {name} | {mode} | " + " | ".join(str(sc[c]) for c in td.CRITERIA) + f" | {req} | {warn} | {req_b} | {se} | {nw} |")
for name, mode, st, ev, ev_b in detail:
    L += ["", f"## {name} ({td.CODE_MIX_MODES[mode]['label']})", ""]
    for s in st.scenes:
        for k, t in enumerate(s.turns):
            L.append(f"- `{s.id}_{k + 1}` **{bible.characters[t.speaker].name}:** {t.text}")
    L += ["", "Evidence:"] + [f"- {c}: {ev['evidence'][c] if isinstance(ev['evidence'][c], str) else '; '.join(ev['evidence'][c]) or 'none'}"
                              for c in td.CRITERIA]
    iss = {(w["rule"], w["where"], w["problem"]): w for w in ev["issues"] + ev_b["issues"]}
    L += ["", "Critic findings (own mode + natural mode):"] + \
         [f"- {'ERROR' if w['required'] else 'warn'} {w['rule']} {w['where']}: {w['problem']} — {w['evidence'][:90]}"
          for w in iss.values()] or ["- none"]
out.write_text("\n".join(L) + "\n")
print("\n".join(L[:4 + 2 + len(rows)]))
print(f"→ {out}")
